const assert=require('node:assert/strict');
const E=require('../src/engine.js');
const cfg=require('../assessment-packs/cmdb-health.json');
assert.equal(cfg.criteria.length,23);
assert.equal(cfg.domains.length,4);
assert.equal(cfg.domains.reduce((s,d)=>s+d.weight,0),100);
assert.equal(cfg.criteria.filter(c=>c.critical).length,0);
const c=id=>cfg.criteria.find(q=>q.id===id);
assert.equal(E.criterionScore(c('C01'),{mode:'measured',numerator:81,denominator:100}),81);
assert.equal(E.criterionScore(c('C03'),{mode:'measured',numerator:3,denominator:100}),97);
assert.equal(E.criterionScore(c('C01'),{mode:'self',maturity:3}),75);
assert.equal(E.criterionScore(c('C23'),{mode:'measured',maturity:4}),100);
assert.equal(E.criterionScore(c('C01'),{mode:'measured',numerator:11,denominator:10}),null);
const answer={};
for(const q of cfg.criteria)answer[q.id]=q.metricType==='maturity'?{mode:'measured',maturity:4,assurance:'verified'}:{mode:'measured',numerator:q.metricType==='lower'?0:100,denominator:100,assurance:'verified'};
let r=E.calculate(cfg,answer);
assert.equal(r.overall,100);
assert.equal(r.coverage,100);
assert.equal(r.maturityBand,'Optimised');
assert.equal(r.reviewCoverage,100);
answer.C10={mode:'unknown'};
assert.ok(E.calculate(cfg,answer).coverage<100);
for(const q of cfg.criteria)answer[q.id]={mode:'self',maturity:2};
r=E.calculate(cfg,answer);
assert.equal(r.overall,50);
assert.equal(r.maturityBand,'Establishing');
assert.equal(r.reviewCoverage,0);
console.log('Scoring tests passed');
